#!/usr/bin/env node
/**
 * 10-build-registry.mjs — replaces the hand-maintained designed-screens.json.
 *
 *   node 10-build-registry.mjs <flows-dir> [--write]
 *
 * The old file was a committed list with a note saying "regenerate with the
 * snippet in webapp/README.md". Nobody ran it, so it reported 87 of 205 on a
 * build where all 205 render. A registry that is computed cannot drift.
 * Wire this into the build and delete the committed file.
 */
import fs from "node:fs";
import path from "node:path";
const FLOWS = process.argv[2], WRITE = process.argv.includes("--write");
const rows = [];
for (const flow of fs.readdirSync(FLOWS, { withFileTypes: true }).filter(d => d.isDirectory())) {
  for (const scr of fs.readdirSync(path.join(FLOWS, flow.name), { withFileTypes: true }).filter(d => d.isDirectory())) {
    const dir = path.join(FLOWS, flow.name, scr.name);
    const html = path.join(dir, "index.html");
    if (!fs.existsSync(html)) continue;
    const src = fs.readFileSync(html, "utf8");
    rows.push({
      route: `${flow.name}/${scr.name}`,
      bytes: src.length,
      hasContract: fs.existsSync(path.join(dir, "screen.json")),
      states: (src.match(/data-state="/g) || []).length,
      placeholder: /(?:lorem ipsum|coming soon|TODO:|FIXME:|not implemented)/i.test(src),
    });
  }
}
const built = rows.filter(r => !r.placeholder);
console.log(`routes with rendered HTML   ${rows.length}`);
console.log(`  carrying a screen.json    ${rows.filter(r => r.hasContract).length}`);
console.log(`  with state markup         ${rows.filter(r => r.states > 0).length}`);
console.log(`  containing placeholders   ${rows.filter(r => r.placeholder).length}`);
console.log(`\nBUILT: ${built.length} of ${rows.length}`);
if (WRITE) {
  fs.writeFileSync("data/screen-registry.json", JSON.stringify({
    _note: "GENERATED by 10-build-registry.mjs at build time. Do not commit a hand-maintained copy.",
    generatedAt: new Date().toISOString(),
    total: rows.length, built: built.length,
    routes: Object.fromEntries(rows.map(r => [r.route, { bytes: r.bytes, hasContract: r.hasContract, states: r.states }])),
  }, null, 2));
  console.log("wrote data/screen-registry.json");
}
