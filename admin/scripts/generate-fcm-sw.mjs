#!/usr/bin/env node
/**
 * Generates public/firebase-messaging-sw.js from env vars at build time.
 *
 * Why this exists: the FCM service worker must sit at the Hosting target's
 * root with no relocation option, and must load as a classic script
 * (`importScripts` + the Firebase *compat* build) — the registration path
 * Firebase's SDK uses does not support `type: "module"`, so it can't reuse
 * the modular SDK imports the rest of the app uses, and it can't read
 * `process.env.NEXT_PUBLIC_*` at runtime the way app code can (files in
 * Next's public/ are copied verbatim, never processed by the bundler). This
 * script is the one source of truth (env vars) instead of hand-maintaining
 * a second copy of the Firebase config inside the service worker file.
 *
 * Runs via the "predev"/"prebuild" npm scripts — see package.json.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");

function loadEnvFile(filename) {
  const path = join(rootDir, filename);
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    if (!(key in process.env)) process.env[key] = value;
  }
}

// .env.local wins over .env, matching Next's own precedence.
loadEnvFile(".env.local");
loadEnvFile(".env");

const required = [
  "NEXT_PUBLIC_FIREBASE_API_KEY",
  "NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN",
  "NEXT_PUBLIC_FIREBASE_PROJECT_ID",
  "NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET",
  "NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID",
  "NEXT_PUBLIC_FIREBASE_APP_ID",
];

if (required.some((key) => !process.env[key])) {
  console.warn(
    "[generate-fcm-sw] Firebase env vars not set — skipping public/firebase-messaging-sw.js generation. " +
      "Background push notifications won't work until .env.local is filled in (see .env.example).",
  );
  process.exit(0);
}

const sw = `// AUTO-GENERATED by scripts/generate-fcm-sw.mjs — do not edit directly.
// Regenerated on every "npm run dev" / "npm run build" from your env vars.
// CDN version pinned below is a manual copy of the "firebase" version in
// package.json — bump both together, they don't stay in sync automatically.
importScripts("https://www.gstatic.com/firebasejs/12.17.1/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/12.17.1/firebase-messaging-compat.js");

firebase.initializeApp({
  apiKey: "${process.env.NEXT_PUBLIC_FIREBASE_API_KEY}",
  authDomain: "${process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN}",
  projectId: "${process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID}",
  storageBucket: "${process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET}",
  messagingSenderId: "${process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID}",
  appId: "${process.env.NEXT_PUBLIC_FIREBASE_APP_ID}",
});

const messaging = firebase.messaging();
messaging.onBackgroundMessage((payload) => {
  const { title, body } = payload.notification || {};
  self.registration.showNotification(title || "MusicLinkd", { body: body || "" });
});
`;

writeFileSync(join(rootDir, "public", "firebase-messaging-sw.js"), sw);
console.log("[generate-fcm-sw] Wrote public/firebase-messaging-sw.js");
