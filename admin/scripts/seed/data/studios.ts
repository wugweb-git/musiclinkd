/** One StudioDoc per filler Studio-type business, so the studios list isn't limited to the 9 named ones. */
export function generateFillerStudios(): SeedStudio[] {
  const rng = makeRng(554433);
  return FILLER_USERS.filter((u) => u.data.profileType === "BUSINESS" && u.data.businessType === "Studio").map((biz, i) => ({
    id: mockId("studio-filler", biz.data.businessName ?? biz.data.displayName),
    data: {
      ownerUid: biz.id,
      name: biz.data.businessName ?? biz.data.displayName,
      location: biz.data.location,
      rating: Math.round((3.8 + rng() * 1.2) * 10) / 10,
      reviewCount: intBetween(rng, 4, 60),
      hourlyRate: biz.data.hourlyRate,
      verifiedGold: biz.data.isVerified,
      amenities: [pick(rng, STUDIO_AMENITIES), pick(rng, STUDIO_AMENITIES)],
      consoleType: pick(rng, STUDIO_CONSOLE_TYPES),
      imageUrl: `https://images.unsplash.com/photo-${["1511671782779-c97d3d27a1d4", "1514525253161-7a46d19cd819", "1470225620780-dba8ba36b745", "1465847899084-d164df4dedc6"][i % 4]}?w=800`,
      createdAt: onDate("2026-07-20"),
      services: [pick(rng, STUDIO_SERVICES)],
    },
  }));
}

export const ALL_STUDIOS: SeedStudio[] = [...NAMED_STUDIOS, ...generateFillerStudios()];
