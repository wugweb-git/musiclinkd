/** Procedurally generated TALENT filler profiles rounding out the directory. Deterministic (seeded rng), not Math.random(). */
export function generateFillerUsers(count: number): SeedUser[] {
  const rng = makeRng(20260812);
  const totalWeight = FILLER_CATEGORIES.reduce((sum, c) => sum + c.weight, 0);
  const out: SeedUser[] = [];
  const usedNames = new Set<string>();

  for (let i = 0; i < count; i++) {
    const first = pick(rng, FIRST_NAMES);
    let last = pick(rng, LAST_NAMES);
    let fullName = `${first} ${last}`;
    let attempts = 0;
    while (usedNames.has(fullName) && attempts < 10) {
      last = pick(rng, LAST_NAMES);
      fullName = `${first} ${last}`;
      attempts++;
    }
    usedNames.add(fullName);

    let roll = rng() * totalWeight;
    let roleLabel: keyof typeof PERSON_TYPE_SLUGS = "Singer / Vocalist";
    for (const c of FILLER_CATEGORIES) {
      if (roll < c.weight) {
        roleLabel = c.role;
        break;
      }
      roll -= c.weight;
    }
    const secondaryLabel = pick(
      rng,
      FILLER_CATEGORIES.filter((c) => c.role !== roleLabel),
    ).role;

    const genres = pickN(rng, GENRES, intBetween(rng, 1, 3));
    const languages = pickN(rng, LANGUAGES, intBetween(rng, 1, 2));
    const instruments = pickN(rng, INSTRUMENTS, intBetween(rng, 0, 2));
    const badges = pickN(rng, PERSONA_BADGES, intBetween(rng, 1, 2));
    const verified = rng() > 0.4;

    out.push({
      id: mockId("talent-filler", fullName),
      data: {
        displayName: fullName,
        email: `${first.toLowerCase()}.${last.toLowerCase()}.${i}@musiclinkd-mock.example`,
        primaryRole: PERSON_TYPE_SLUGS[roleLabel],
        secondaryRole: PERSON_TYPE_SLUGS[secondaryLabel],
        isVerified: verified,
        isBanned: false,
        isAvailable: rng() > 0.15,
        hourlyRate: intBetween(rng, 12, 55) * 100,
        budgetTier: pick(rng, BUDGET_TIERS),
        location: pick(rng, CITIES),
        bio: `${roleLabel} based in ${pick(rng, CITIES).split(",")[0]}, working across ${genres.join(" and ")}.`,
        gender: pick(rng, ["Male", "Female"] as const),
        genres,
        languages,
        instruments,
        personaBadges: badges,
        trustBadges: verified ? pickN(rng, TRUST_BADGES, 1) : [],
        avatarUrl: avatar(i),
        createdAt: onDate("2026-07-15"),
        profileType: "TALENT",
        vocalRange: roleLabel === "Singer / Vocalist" ? pick(rng, VOCAL_RANGES) : undefined,
        dawStack: roleLabel === "Music Producer" || roleLabel === "Sound Engineer" ? pickN(rng, DAW_TOOLS, 2) : undefined,
        sessionAvailability: pick(rng, AVAILABILITY_STATUSES),
      },
    });
  }
  return out;
}

