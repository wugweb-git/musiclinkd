type SeedPortfolio = { id: string; data: PortfolioProjectDoc };
type SeedProject = { id: string; data: ProjectDoc };

function portfolio(
  ownerUid: string,
  name: string,
  extra: Partial<PortfolioProjectDoc> & Pick<PortfolioProjectDoc, "description" | "type" | "releaseDate" | "ownerRoles" | "artworkTheme">,
): SeedPortfolio {
  return {
    id: mockId("portfolio", `${ownerUid}-${name}`),
    data: {
      ownerUid,
      name,
      status: "Released",
      visibility: "Public",
      collaborators: [],
      credits: [],
      projectViews: extra.projectViews ?? 1200,
      likes: extra.likes ?? 180,
      shares: extra.shares ?? 24,
      createdAt: onDate("2026-05-01"),
      lastUpdatedAt: onDate("2026-06-01"),
      ...extra,
    },
  };
}

