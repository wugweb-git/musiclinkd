function openProject(
  id: string,
  creatorUid: string,
  title: string,
  roleRequired: string,
  budget: string,
  extra: Partial<ProjectDoc>,
): SeedProject {
  return {
    id: mockId("project", id),
    data: {
      creatorUid,
      title,
      roleRequired,
      budget,
      status: "OPEN",
      genres: [],
      applicantCount: 0,
      createdAt: onDate("2026-07-25"),
      ...extra,
    },
  };
}

